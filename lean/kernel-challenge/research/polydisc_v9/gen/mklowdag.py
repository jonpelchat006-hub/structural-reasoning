"""V9/LowDag.lean: the low-part graph (natdag%) and its kernel rfl link to the structured lowRun."""
import sys, random
sys.path.insert(0, "/home/claude/v9dev/gen")
from lowdag2 import build, zenc
import reference_answers as ref
random.seed(5); n = random.randint(2 ** 57, 2 ** 63)
P = ref.candidate_polynomial(n)[0]
g, res, bad = build([zenc(c) for c in P])
F25 = " ".join(f"f{i}" for i in range(25)); FL = ", ".join(f"f{i}" for i in range(25))
body = "\n".join(g.lines) + f"\napp x25 {g.tok(res)} {g.tok(bad)}"
src = f'''import V9.Dag
import V9.Low

namespace V9

/-- The low-part run as one shared graph (generated by `gen/mklowdag.py` from `lowRun`). -/
def lowDag ({F25} : Nat) : Nat × Nat :=
  natdag% "{body}" [{FL}, (@Prod.mk Nat Nat), dbTab]

def LowDagEq : Prop := ∀ {F25} : Nat, lowDag {F25} = lowRun [{FL}]

open Lean Elab Term Command Meta in
run_cmd liftTermElabM do
  let ty ← instantiateMVars (← elabTerm (← `(LowDagEq)) none)
  let pf ← instantiateMVars (← elabTerm (← `(fun ({F25} : Nat) => @rfl (Nat × Nat) (lowDag {F25}))) none)
  addDecl (.thmDecl {{ name := `V9.lowDag_eq, levelParams := [], type := ty, value := pf }})

end V9
'''
open("/home/claude/v9dev/V9/LowDag.lean", "w").write(src)
print("nodes", len(g.lines), "bytes", len(src))
# a concrete test: the expected value
want = ref.polynomial_discriminant(P)
open("/home/claude/v9dev/gen/test_case.txt", "w").write(" ".join(str(zenc(c)) for c in P) + "\n" + str(zenc(want)) + "\n")
